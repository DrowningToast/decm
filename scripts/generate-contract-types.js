#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// Configuration
const CONTRACTS_DIR = path.join(__dirname, '../apps/contracts/out');
const OUTPUT_DIR = path.join(__dirname, '../apps/web/src/contracts');
const MAIN_CONTRACTS = [
  'Event.sol',
  'EventAccessManager.sol',
  'EventTicket.sol',
  'EventCertificate.sol',
  'DecmAccessManager.sol'
];

// Ensure output directory exists
if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

console.log('🔨 Generating TypeScript types from contract ABIs...\n');

// Clean up existing files
console.log('🧹 Cleaning up existing files...');
fs.readdirSync(OUTPUT_DIR).forEach(file => {
  if (file.endsWith('.ts') && !file.startsWith('index')) {
    fs.unlinkSync(path.join(OUTPUT_DIR, file));
  }
});

// Generate types for each main contract
MAIN_CONTRACTS.forEach(contractFile => {
  const contractName = contractFile.replace('.sol', '');
  const abiPath = path.join(CONTRACTS_DIR, contractFile, `${contractName}.json`);
  
  if (fs.existsSync(abiPath)) {
    console.log(`📝 Processing ${contractName}...`);
    
    // Read ABI
    const contractJson = JSON.parse(fs.readFileSync(abiPath, 'utf8'));
    const abi = contractJson.abi || contractJson; // Handle both formats
    
    // Generate TypeScript file
    const outputPath = path.join(OUTPUT_DIR, `${contractName}.ts`);
    const content = generateTypeScriptContent(contractName, abi);
    
    fs.writeFileSync(outputPath, content);
    console.log(`✅ Generated ${outputPath}`);
  } else {
    console.log(`⚠️  ABI not found for ${contractName} at ${abiPath}`);
  }
});

// Generate index file
console.log('\n📦 Generating index file...');
const indexContent = generateIndexContent(MAIN_CONTRACTS);
fs.writeFileSync(path.join(OUTPUT_DIR, 'index.ts'), indexContent);
console.log('✅ Generated index.ts');

console.log('\n🎉 Contract types generation complete!');

function generateTypeScriptContent(contractName, abi) {
  return `// Auto-generated TypeScript types for ${contractName} contract
// This file is generated by scripts/generate-contract-types.js
// Do not edit this file directly

export const ${contractName}ABI = ${JSON.stringify(abi, null, 2)} as const;

export type ${contractName} = {
  abi: typeof ${contractName}ABI;
};

export default ${contractName}ABI;
`;
}

function generateIndexContent(contracts) {
  const imports = contracts.map(contract => {
    const name = contract.replace('.sol', '');
    return `import { ${name}ABI, ${name} } from './${name}';`;
  }).join('\n');

  const exports = contracts.map(contract => {
    const name = contract.replace('.sol', '');
    return `export { ${name}ABI, ${name} } from './${name}';`;
  }).join('\n');

  return `// Auto-generated index file for contract types
// This file is generated by scripts/generate-contract-types.js
// Do not edit this file directly

${imports}

${exports}

// Re-export all ABIs for convenience
export const ABIs = {
${contracts.map(contract => {
  const name = contract.replace('.sol', '');
  return `  ${name}: ${name}ABI,`;
}).join('\n')}
} as const;
`;
}
