#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

// Configuration
const CONTRACTS_DIR = path.join(__dirname, "../apps/contracts");
const OUTPUT_DIR = path.join(__dirname, "../apps/backend/contracts");
const CONTRACT_ARTIFACTS_DIR = path.join(CONTRACTS_DIR, "out");

// Contract configurations
const CONTRACTS = [
    { 
        name: "Event", 
        solFile: "Event.sol",
        pkgName: "event",
        outputPath: path.join(OUTPUT_DIR, "event")
    },
    { 
        name: "EventAccessManager", 
        solFile: "EventAccessManager.sol",
        pkgName: "accessmanager",
        outputPath: path.join(OUTPUT_DIR, "accessmanager")
    },
    { 
        name: "EventTicket", 
        solFile: "EventTicket.sol",
        pkgName: "ticket",
        outputPath: path.join(OUTPUT_DIR, "ticket")
    },
    { 
        name: "EventCertificate", 
        solFile: "EventCertificate.sol",
        pkgName: "certificate",
        outputPath: path.join(OUTPUT_DIR, "certificate")
    },
    { 
        name: "DecmAccessManager", 
        solFile: "DecmAccessManager.sol",
        pkgName: "decm",
        outputPath: path.join(OUTPUT_DIR, "decm")
    }
];

console.log("🔧 Generating Go bindings from contract artifacts...\n");

// Check if abigen is installed
try {
    console.log("Checking if abigen is installed...");
    execSync("abigen --version", { stdio: "pipe" });
    console.log("✅ abigen is installed\n");
} catch (error) {
    console.error("❌ abigen is not installed or not in PATH");
    console.error("Please install abigen by running:");
    console.error("go install github.com/ethereum/go-ethereum/cmd/abigen@latest");
    console.error("Make sure your GOPATH/bin is in your PATH");
    process.exit(1);
}

// Ensure output directory exists
if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    console.log(`📁 Created output directory: ${OUTPUT_DIR}`);
}

// Create subdirectories for each contract
CONTRACTS.forEach(contract => {
    if (!fs.existsSync(contract.outputPath)) {
        fs.mkdirSync(contract.outputPath, { recursive: true });
    }
});

let allContractsProcessed = true;

// Process each contract
CONTRACTS.forEach(contract => {
    console.log(`\n📝 Processing ${contract.name}...`);
    
    const contractDir = path.join(CONTRACT_ARTIFACTS_DIR, contract.solFile);
    const contractJsonPath = path.join(contractDir, `${contract.name}.json`);
    
    // Check if contract artifact exists
    if (!fs.existsSync(contractJsonPath)) {
        console.log(`❌ Contract artifact not found for ${contract.name} at ${contractJsonPath}`);
        allContractsProcessed = false;
        return;
    }
    
    try {
        // Read contract JSON to extract ABI and BIN
        const contractJson = JSON.parse(fs.readFileSync(contractJsonPath, "utf8"));
        const abi = contractJson.abi;
        const bin = contractJson.bytecode.object;
        
        // Create temporary files for ABI and BIN
        const tempAbiPath = path.join(contract.outputPath, `${contract.name}.abi`);
        const tempBinPath = path.join(contract.outputPath, `${contract.name}.bin`);
        
        fs.writeFileSync(tempAbiPath, JSON.stringify(abi));
        fs.writeFileSync(tempBinPath, bin);
        
        // Generate Go binding
        const goFilePath = path.join(contract.outputPath, `${contract.name}.go`);
        const command = `abigen --abi="${tempAbiPath}" --bin="${tempBinPath}" --pkg="${contract.pkgName}" --out="${goFilePath}" --type="${contract.name}"`;
        
        console.log(`Running: ${command}`);
        execSync(command, { stdio: "pipe" });
        
        // Clean up temporary files
        fs.unlinkSync(tempAbiPath);
        fs.unlinkSync(tempBinPath);
        
        console.log(`✅ Generated Go binding for ${contract.name} at ${goFilePath}`);
        
        // Add package documentation
        const goContent = fs.readFileSync(goFilePath, "utf8");
        const documentedContent = `// Package ${contract.pkgName} contains Go bindings for the ${contract.name} smart contract.
// This file is auto-generated by scripts/generate-go-bindings.js
// Do not edit this file directly

${goContent}`;
        
        fs.writeFileSync(goFilePath, documentedContent);
        
    } catch (error) {
        console.error(`❌ Failed to generate Go binding for ${contract.name}:`);
        console.error(error.message);
        allContractsProcessed = false;
    }
});

if (allContractsProcessed) {
    console.log("\n🎉 All Go bindings generated successfully!");
    
    // Generate an index file for easy importing
    console.log("\n📦 Generating index file...");
    const indexContent = generateIndexContent(CONTRACTS);
    fs.writeFileSync(path.join(OUTPUT_DIR, "contracts.go"), indexContent);
    console.log("✅ Generated contracts.go index file");
    
    process.exit(0);
} else {
    console.log("\n❌ Some Go bindings could not be generated.");
    process.exit(1);
}

function generateIndexContent(contracts) {
    const imports = contracts
        .map(contract => {
            return `    "apps/backend/contracts/${contract.pkgName}"`;
        })
        .join("\n");
    
    return `// Package contracts provides a unified import for all smart contract bindings.
// This file is auto-generated by scripts/generate-go-bindings.js
// Do not edit this file directly

package contracts

import (
${imports}
)

// ContractBindings holds all contract bindings
type ContractBindings struct {
    Event              *event.Event
    EventAccessManager *accessmanager.EventAccessManager
    EventTicket        *ticket.EventTicket
    EventCertificate   *certificate.EventCertificate
    DecmAccessManager  *decm.DecmAccessManager
}
`;
}
